"""scrapers/_role.derive_role の単体テスト"""

from __future__ import annotations

import pytest

from src.scrapers._role import derive_role


@pytest.mark.parametrize(
    ("affiliation", "expected"),
    [
        # 委員長系
        ("内閣委員長", "委員長"),
        ("法務委員長", "委員長"),
        ("予算委員長", "委員長"),
        ("衆議院議長", "委員長"),
        ("参議院副議長", "委員長"),
        ("委員長", "委員長"),
        # 委員長 (PR3 拡張: 臨時委員長 / 事務総長 / 副議長 / 複合)
        ("臨時委員長", "委員長"),
        ("事務総長", "委員長"),
        ("衆議院事務総長", "委員長"),
        ("参議院事務総長", "委員長"),
        ("副議長", "委員長"),
        ("法務委員長 自由民主党", "委員長"),  # multi-token, 委員長 が左側
        # 答弁者系（大臣）
        ("内閣総理大臣", "答弁者"),
        ("経済産業大臣", "答弁者"),
        ("財務副大臣", "答弁者"),
        ("外務大臣政務官", "答弁者"),
        # 政府参考人系
        ("厚生労働省医政局長", "政府参考人"),
        ("内閣官房副長官", "政府参考人"),
        ("内閣府審議官", "政府参考人"),
        ("総務省事務次長", "政府参考人"),
        # 参考人
        ("参考人", "参考人"),
        ("経団連参考人", "参考人"),
        # 質疑者（政党所属）
        ("自由民主党", "質疑者"),
        ("立憲民主党", "質疑者"),
        ("チームみらい", "質疑者"),
        ("自由民主党・無所属の会", "質疑者"),
        ("無所属", "質疑者"),
        # その他
        ("", "その他"),
        ("不明", "その他"),
    ],
)
def test_derive_role(affiliation: str, expected: str) -> None:
    assert derive_role(affiliation) == expected
